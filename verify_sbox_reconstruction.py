def reconstruct_fused_value(sbox_output, positions):
    """Reconstruct a 32-bit fused table value from 4-bit S-box output and P-box positions."""
    result = 0
    for bit_idx, pos in enumerate(positions):
        if (sbox_output >> bit_idx) & 1:
            result |= 1 << pos
    return result


def verify_all_tables():
    """Verify that we can reconstruct all fused tables from extracted S-boxes."""
    all_correct = True

    for table_num in range(8):
        fused_table = FUSED_TABLES[table_num]
        custom_sbox = CUSTOM_SBOXES[table_num]
        positions = PBOX_POSITIONS[table_num]

        print(f"\nVerifying SBOX{table_num + 9}...")

        errors = []
        for i in range(64):
            expected = fused_table[i]
            sbox_output = custom_sbox[i]
            reconstructed = reconstruct_fused_value(sbox_output, positions)

            if reconstructed != expected:
                errors.append((i, expected, reconstructed))

        if errors:
            print(f"  ERROR: {len(errors)} mismatches found!")
            for idx, expected, reconstructed in errors[:5]:  # Show first 5 errors
                print(f"    Index {idx}: expected {expected}, got {reconstructed}")
            all_correct = False
        else:
            print(f"  SUCCESS: All 64 entries match perfectly!")

    return all_correct


